  var LANG_NAMES = { ru: 'Русский', en: 'English' };
  var current = 'ru';

  function normalize(lang) {
    var code = String(lang || '').toLowerCase().split(/[-_]/)[0];
    if (code === 'ru' || code === 'be' || code === 'uk' || code === 'kk') return 'ru';
    if (code === 'en') return 'en';
    return 'en';
  }

  function t(key, params) {
    var table = STRINGS[current] || STRINGS.ru;
    var value = table[key];
    if (value === undefined) value = STRINGS.ru[key];
    if (value === undefined) return key;
    if (params) {
      value = value.replace(/\{(\w+)\}/g, function (m, name) {
        return params[name] !== undefined ? String(params[name]) : m;
      });
    }
    return value;
  }

  function setLang(lang) {
    current = normalize(lang);
    if (root && root.document && root.document.documentElement) {
      root.document.documentElement.lang = current;
    }
    return current;
  }

  function getLang() { return current; }
  function otherLang() { return current === 'ru' ? 'en' : 'ru'; }

  function apply(rootEl) {
    var scope = rootEl || (root && root.document);
    if (!scope || !scope.querySelectorAll) return;
    var nodes = scope.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) {
      var key = nodes[i].getAttribute('data-i18n');
      var value = t(key);
      if (nodes[i].hasAttribute('data-i18n-html')) nodes[i].innerHTML = value;
      else nodes[i].textContent = value;
    }
    var aria = scope.querySelectorAll('[data-i18n-aria]');
    for (var j = 0; j < aria.length; j++) {
      aria[j].setAttribute('aria-label', t(aria[j].getAttribute('data-i18n-aria')));
    }
    var ph = scope.querySelectorAll('[data-i18n-placeholder]');
    for (var k = 0; k < ph.length; k++) {
      ph[k].setAttribute('placeholder', t(ph[k].getAttribute('data-i18n-placeholder')));
    }
  }

  root.I18n = {
    t: t,
    setLang: setLang,
    getLang: getLang,
    otherLang: otherLang,
    normalize: normalize,
    apply: apply,
    LANG_NAMES: LANG_NAMES,
    STRINGS: STRINGS
  };
