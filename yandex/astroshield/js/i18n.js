  const DICTS = { ru: ru, en: en, tr: tr };
  const LOCALES = { ru: "ru-RU", en: "en-US", tr: "tr-TR" };
  const LANG_NAMES = { ru: "Русский", en: "English", tr: "Türkçe" };

  let lang = "ru";

  function normalize(code) {
    const base = String(code || "").toLowerCase().split(/[-_]/)[0];
    if (base === "ru" || base === "be" || base === "kk" || base === "uk" || base === "uz" || base === "ky" || base === "tg") {
      return "ru";
    }
    if (base === "tr") return "tr";
    return "en";
  }

  function setLang(code) {
    lang = DICTS[code] ? code : normalize(code);
    document.documentElement.lang = lang;
    const bootTitle = document.getElementById("bootTitle");
    const bootSub = document.getElementById("bootSubtitle");
    const bootHint = document.getElementById("bootHint");
    if (bootTitle) bootTitle.textContent = t("brand");
    if (bootSub) bootSub.textContent = t("subtitle");
    if (bootHint) bootHint.textContent = t("loading");
    return lang;
  }

  function t(key, vars) {
    const dict = DICTS[lang] || en;
    let value = dict[key];
    if (value === undefined) value = en[key];
    if (value === undefined) return key;
    if (Array.isArray(value)) return value.slice();
    if (typeof value !== "string") return value;
    if (vars) {
      for (const k in vars) {
        value = value.split("{" + k + "}").join(String(vars[k]));
      }
    }
    return value;
  }

  function arr(key) {
    const v = t(key);
    return Array.isArray(v) ? v : [];
  }

  function num(n, digits) {
    const d = typeof digits === "number" ? digits : 0;
    try {
      return Number(n).toLocaleString(LOCALES[lang] || "ru-RU", {
        minimumFractionDigits: d,
        maximumFractionDigits: d
      });
    } catch (e) {
      return String(Math.round(Number(n) * Math.pow(10, d)) / Math.pow(10, d));
    }
  }

  function combo(n) {
    try {
      return Number(n).toLocaleString(LOCALES[lang] || "ru-RU", {
        minimumFractionDigits: 1,
        maximumFractionDigits: 1
      });
    } catch (e) {
      return Number(n).toFixed(1);
    }
  }

  function clock(seconds) {
    const s = Math.max(0, Math.floor(seconds));
    const m = Math.floor(s / 60);
    return m + ":" + String(s % 60).padStart(2, "0");
  }

  AG.I18N = {
    normalize: normalize,
    setLang: setLang,
    get lang() { return lang; },
    t: t,
    arr: arr,
    num: num,
    combo: combo,
    clock: clock,
    locale: function () { return LOCALES[lang] || "ru-RU"; },
    langNames: LANG_NAMES,
    languages: ["ru", "en", "tr"]
  };
